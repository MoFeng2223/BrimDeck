using System.Text.Json;
using BrimDeck.Core;

internal static class InputMethodTests
{
    internal static void Run(Action<string, bool> check)
    {
        var wechat = new InputMethodInfo("wechat", "微信输入法");
        var rime = new InputMethodInfo("rime", "小狼毫");
        var settings = new InputMethodSettings { Profiles = [new() { Id = "rime", Name = rime.Name }, new() { Id = "missing", Name = "Removed" }, new() { Id = "wechat", Enabled = false }] };
        check("IME module starts disabled", !settings.Enabled);
        check("IME unavailable and excluded profiles are skipped", settings.Participants([wechat, rime]).Select(p => p.Id).SequenceEqual(["rime"]));
        check("IME removed profile remains saved", settings.Profiles.Any(p => p.Id == "missing"));
        settings.Profiles[2].Enabled = true;
        check("IME participant order follows settings", settings.Participants([wechat, rime]).Select(p => p.Id).SequenceEqual(["rime", "wechat"]));
        check("IME newly installed profiles are not auto selected", settings.Participants([wechat, rime, new("new", "New")]).Count == 2);
        var cycle = new InputMethodCycle([wechat, rime], wechat.Id);
        check("IME first tap previews next profile", cycle.Next() == rime);
        check("IME cycle wraps to the first item", cycle.Next() == wechat);
        cycle.Next();
        check("IME commits only the final preview", cycle.Commit() == rime);
        check("IME cannot submit a session twice", cycle.Commit() is null && cycle.Next() is null);
        var excluded = new InputMethodCycle([wechat, rime], "other");
        check("IME current excluded starts at first participant", excluded.Next() == wechat);
        excluded.Cancel();
        check("IME cancelled selection cannot commit", excluded.Commit() is null);
        var one = new InputMethodCycle([rime], rime.Id);
        check("IME one participant remains selectable", one.Next() == rime && one.Commit() == rime);
        var empty = new InputMethodCycle([], wechat.Id);
        check("IME empty list cannot produce a selection", empty.Next() is null && empty.Commit() is null);
        var mutable = new List<InputMethodInfo> { wechat, rime };
        var snapshot = new InputMethodCycle(mutable, wechat.Id);
        mutable.Clear();
        check("IME session snapshots the participant list", snapshot.Items.Count == 2);
        settings.Profiles.Add(new() { Id = "RIME" }); settings.Profiles.Add(new() { Id = "" });
        settings.Normalize();
        check("IME settings normalize duplicates without reordering", settings.Profiles.Select(p => p.Id).SequenceEqual(["rime", "missing", "wechat"]));
        var copied = JsonSerializer.Deserialize<InputMethodSettings>(JsonSerializer.Serialize(settings))!;
        check("IME settings survive serialization", copied.Profiles.Select(p => p.Id).SequenceEqual(settings.Profiles.Select(p => p.Id)));
        var deck = new DeckSettings { InputMethods = settings };
        var deckCopy = deck.Copy(); deckCopy.InputMethods.Profiles[0].Enabled = false;
        check("IME settings copy owns its profile objects", deck.InputMethods.Profiles[0].Enabled && !deckCopy.InputMethods.Profiles[0].Enabled);
        var old = JsonSerializer.Deserialize<DeckSettings>("{}")!; old.Normalize();
        check("IME older settings keep the module disabled", !old.InputMethods.Enabled && old.InputMethods.Profiles.Count == 0);
        var nullSettings = JsonSerializer.Deserialize<DeckSettings>("{\"InputMethods\":null}")!; nullSettings.Normalize();
        check("IME null configuration normalizes safely", !nullSettings.InputMethods.Enabled);

        var legacy = JsonSerializer.Deserialize<DeckSettings>("{\"InputMethods\":{\"Enabled\":true,\"Shortcut\":\"Ctrl+Shift\"}}")!; legacy.Normalize();
        check("IME existing enabled configurations retain control mode", legacy.InputMethods.Enabled && legacy.InputMethods.Mode == InputMethodMode.Control && legacy.InputMethods.Shortcut == "Ctrl+Shift");
        settings.Mode = InputMethodMode.Notify;
        check("IME mode survives serialization", JsonSerializer.Deserialize<InputMethodSettings>(JsonSerializer.Serialize(settings))!.Mode == InputMethodMode.Notify);
        check("IME settings copy preserves notification mode and control choices", new DeckSettings { InputMethods = settings }.Copy().InputMethods is { Mode: InputMethodMode.Notify, Profiles.Count: 3 });
        settings.Mode = (InputMethodMode)99; settings.Normalize();
        check("IME invalid mode safely returns to existing control behavior", settings.Mode == InputMethodMode.Control);
        var changes = new InputMethodChanges();
        check("IME notification ignores unreadable startup state", changes.Observe(null, 0) is null);
        check("IME notification establishes a silent initial baseline", changes.Observe("wechat", 0) is null);
        check("IME notification ignores repeated and case-only state", changes.Observe("WECHAT", 200) is null);
        check("IME notification waits for a stable new profile", changes.Observe("rime", 300) is null && changes.Observe("rime", 400) is null);
        check("IME notification reports a verified stable change once", changes.Observe("rime", 450) == "rime" && changes.Observe("rime", 700) is null);
        changes.Observe("wechat", 800); changes.Observe("japanese", 900);
        check("IME rapid changes discard intermediate candidates", changes.Observe("japanese", 1000) is null && changes.Observe("japanese", 1050) == "japanese");
        changes.Observe("rime", 1100);
        check("IME returning to the current profile cancels a pending notice", changes.Observe("japanese", 1300) is null && changes.Observe("japanese", 1500) is null);
        changes.Observe("rime", 1600);
        check("IME notification waits while switching modifiers are held", changes.Observe("rime", 1900, defer: true) is null);
        check("IME releasing modifiers reports only the final stable item", changes.Observe("rime", 1901) == "rime");
        changes.Observe("wechat", 2000); changes.Observe(null, 2100);
        check("IME interrupted reads require a fresh stable candidate", changes.Observe("wechat", 2400) is null && changes.Observe("wechat", 2550) == "wechat");
        changes.Reset();
        check("IME changing mode or resuming creates a new silent baseline", changes.Observe("japanese", 3000) is null && changes.Observe("japanese", 3400) is null);
        changes.Observe("rime", 4000);
        check("IME a reversed timestamp cannot emit a stale candidate", changes.Observe("rime", 3900) is null);

        var keys = new InputMethodKeys();
        check("IME Win down always passes through", !keys.Handle(0x5B, true).Block);
        var first = keys.Handle(0x20, true);
        check("IME Win Space requests first preview and menu masking", first.Block && first.Next && first.MaskMenu);
        check("IME typematic does not advance selection", keys.Handle(0x20, true) is { Block: true, Next: false });
        check("IME Win up commits without being swallowed", keys.Handle(0x5B, false) is { Block: false, Commit: true });
        check("IME Space up remains swallowed after Win up", keys.Handle(0x20, false).Block);
        check("IME duplicate Win up cannot commit", !keys.Handle(0x5B, false).Commit);
        keys = new(); keys.Handle(0x5C, true); keys.Handle(0x20, true); keys.Handle(0x20, false); keys.Handle(0x5B, true);
        check("IME both Win keys wait for the final release", !keys.Handle(0x5C, false).Commit && keys.Handle(0x5B, false).Commit);
        keys = new(); keys.Handle(0x5B, true);
        check("IME unavailable module leaves Win Space to Windows", keys.Handle(0x20, true, canStart: false) == default);
        keys.Handle(0x20, false); keys.Handle(0xA2, true);
        check("IME additional modifiers pass through", keys.Handle(0x20, true) == default);
        keys = new(); keys.Handle(0x5B, true); keys.Handle(0x20, true);
        check("IME other shortcut cancels the preview", keys.Handle(0x45, true).Cancel && !keys.Handle(0x5B, false).Commit);
        check("IME cancellation preserves swallowed Space pair", keys.Handle(0x20, false).Block);
        keys = new(); keys.Handle(0x5B, true, injected: true);
        check("IME injected keys cannot start a physical session", keys.Handle(0x20, true) == default);
        keys = new(); keys.SeedHeldKey(0x20); keys.Handle(0x5B, true);
        check("IME already held Space does not become a fresh tap", keys.Handle(0x20, true) == default);
        keys = new(); keys.Handle(0x5B, true); keys.Handle(0x20, true); keys.AbortUnblockedSpace();
        check("IME masking failure leaves original Space up intact", !keys.Handle(0x20, false).Block && !keys.Handle(0x5B, false).Commit);
        keys = new(); keys.Handle(0x5B, true); keys.Handle(0x20, true, canStart: false); keys.Handle(0x20, false);
        check("IME readiness cannot hijack an existing Windows switcher hold", keys.Handle(0x20, true, canStart: true) == default);
        keys.Handle(0x20, false); keys.Handle(0x5B, false); keys.Handle(0x5B, true);
        check("IME next Win hold can use newly ready module", keys.Handle(0x20, true) is { Block: true, Next: true, MaskMenu: true });

        check("IME default shortcut preserves Win Space for older configurations", old.InputMethods.Shortcut == "Win+Space");
        settings.Shortcut = "Ctrl+Shift";
        check("IME modifier chord survives settings copy", new DeckSettings { InputMethods = settings }.Copy().InputMethods.Shortcut == "Ctrl+Shift");
        check("IME shortcut canonicalizes aliases and order", InputMethodBinding.Normalize(" shift + Control + space ") == "Ctrl+Shift+space");
        check("IME modifier-only chord normalizes", InputMethodBinding.Normalize("Shift+Control") == "Ctrl+Shift");
        check("IME shortcut rejects missing or repeated modifiers", InputMethodBinding.Normalize("Ctrl") == "" && InputMethodBinding.Normalize("Ctrl+Control+Space") == "");
        check("IME shortcut rejects multiple main keys", InputMethodBinding.Normalize("Ctrl+A+B") == "");
        keys = new(new(HotkeyModifiers.Ctrl, 0x20)); keys.Handle(0xA2, true);
        check("IME custom Ctrl Space begins without Win menu masking", keys.Handle(0x20, true) is { Begin: true, Next: true, Block: true, MaskMenu: false });
        keys.Handle(0x20, false);
        check("IME custom chord cycles once per tap", keys.Handle(0x20, true) is { Begin: false, Next: true });
        check("IME custom chord commits when its hold modifier releases", keys.Handle(0xA2, false) is { Commit: true, Block: false });
        check("IME custom trigger-up remains owned after modifier release", keys.Handle(0x20, false).Block);
        keys = new(new(HotkeyModifiers.Ctrl | HotkeyModifiers.Shift, 0x4B)); keys.Handle(0xA3, true); keys.Handle(0xA1, true);
        check("IME multi-modifier shortcut supports right-hand keys", keys.Handle(0x4B, true) is { Begin: true, Next: true });
        keys.Handle(0x4B, false);
        check("IME releasing a required modifier commits only once", keys.Handle(0xA1, false).Commit && !keys.Handle(0xA3, false).Commit);
        keys = new(new(HotkeyModifiers.Ctrl, 0xA0)); keys.Handle(0xA2, true);
        check("IME Ctrl Shift takes over the Shift trigger", keys.Handle(0xA1, true) is { Begin: true, Next: true, Block: true });
        check("IME releasing Shift keeps Ctrl Shift selection open", keys.Handle(0xA1, false) is { Block: true, Commit: false });
        check("IME tapping Shift again advances selection", keys.Handle(0xA0, true) is { Next: true, Begin: false });
        check("IME Ctrl Shift confirms on Ctrl release", keys.Handle(0xA2, false) is { Commit: true, Block: false });
        check("IME Ctrl Shift preserves the blocked Shift release", keys.Handle(0xA0, false).Block);
        keys = new(new(HotkeyModifiers.Ctrl, 0xA0)); keys.Handle(0xA0, true);
        check("IME modifier chord accepts the reverse press order", keys.Handle(0xA3, true) is { Next: true, Begin: true, Block: true });
        check("IME reverse chord keeps selection open after tap release", keys.Handle(0xA3, false) is { Block: true, Commit: false });
        keys.Handle(0xA2, true); keys.Handle(0xA2, false);
        check("IME reverse chord confirms once on the held modifier release", keys.Handle(0xA0, false).Commit && !keys.Handle(0xA0, false).Commit);
        keys = new(new(HotkeyModifiers.Alt, 0x4B)); keys.Handle(0xA4, true);
        check("IME Alt combinations request menu masking", keys.Handle(0x4B, true) is { MaskMenu: true, Begin: true });
        keys.Handle(0x4B, false); keys.Cancel();
        check("IME cancelled hold cannot immediately start another session", !keys.Handle(0x4B, true).Next);

        var recorder = new InputMethodRecordingKeys();
        check("IME recorder owns Win down", recorder.Handle(0x5B, true).Block);
        check("IME recorder captures reserved Win Space before system", recorder.Handle(0x20, true) is { Block: true, Modifiers: HotkeyModifiers.Win, Key: 0x20, Complete: false });
        check("IME recorder waits for trigger release", recorder.Handle(0x20, false) is { Block: true, Complete: false });
        check("IME recorder completes only after all keys release", recorder.Handle(0x5B, false) is { Block: true, Complete: true, Modifiers: HotkeyModifiers.Win, Key: 0x20 });
        check("IME recorder finishes without consuming later typing", !recorder.Handle(0x41, true).Block);
        recorder = new(); recorder.Handle(0xA3, true); recorder.Handle(0xA1, true);
        check("IME modifier-only recording waits through first release", recorder.Handle(0xA1, false) is { Block: true, Complete: false });
        check("IME recorder captures Ctrl Shift on final release", recorder.Handle(0xA3, false) is { Complete: true, Key: 0, Modifiers: HotkeyModifiers.Ctrl | HotkeyModifiers.Shift });
        recorder = new(); recorder.Handle(0x1B, true);
        check("IME Esc cancels recording after release", recorder.Handle(0x1B, false) is { Block: true, Complete: true, Cancel: true });
        recorder = new(); recorder.SeedHeldKey(0x0D);
        check("IME recorder lets an existing key-up reach its owner", !recorder.Handle(0x0D, false).Block);
        recorder.Handle(0xA2, true); recorder.Handle(0x4B, true); recorder.Handle(0xA2, false);
        check("IME recorder preserves candidate when modifiers release first", recorder.Handle(0x4B, false) is { Complete: true, Key: 0x4B, Modifiers: HotkeyModifiers.Ctrl });
        recorder = new(); recorder.Handle(0x5B, true, injected: true); recorder.Handle(0x20, true); var injected = recorder.Handle(0x20, false);
        check("IME recorder ignores injected modifiers", injected is { Complete: true, Modifiers: 0, Key: 0x20 });
    }
}
